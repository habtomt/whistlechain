/* WhistleChain frontend app logic (plain JS + ethers.js v6, no build step). */

const STAKE_TOKEN_DECIMALS = 18;

// UZH Ethereum Proof-of-Stake (PoS) test network
const UZH_ETH_POS = {
  chainId: "0x1123F", // 70207 in hex
  chainName: "UZH_ETH_PoS",
  nativeCurrency: { name: "UZHETHs", symbol: "UZHETHs", decimals: 18 },
  rpcUrls: ["https://rpc.uzheths.ifi.uzh.ch"],
  blockExplorerUrls: ["https://explorer.uzheths.ifi.uzh.ch"],
};

let provider, signer, signerAddress;
let contracts = {}; // { token, reputation, governance, treasury, registry } 
let addresses = {};

// Bootstrap: load ABIs + addresses generated by scripts/deploy.js
async function loadContractMeta() {
  addresses = await (await fetch("./contracts/addresses.json")).json();
  const abiNames = {
    token: "WhistleChainToken",
    reputation: "Reputation",
    governance: "Governance",
    treasury: "Treasury",
    registry: "ReportRegistry",
  };
  const abis = {};
  for (const [key, fileBase] of Object.entries(abiNames)) {
    abis[key] = await (await fetch(`./contracts/${fileBase}.abi.json`)).json();
  }
  return { abis, abiNames };
}

async function getReadProvider() {
  // Falls back to a public JSON-RPC provider pointed at whatever network
  // the deployment addresses were generated for, using window.ethereum if
  // present (read-only calls do not require the user's wallet to be unlocked).
  if (window.ethereum) {
    return new ethers.BrowserProvider(window.ethereum);
  }
  throw new Error("No injected wallet found. Install MetaMask or use a wallet-enabled browser.");
}

async function initContracts() {
  const { abis } = await loadContractMeta();
  const readProvider = provider || (await getReadProvider());
  contracts = {
    token: new ethers.Contract(addresses.WhistleChainToken, abis.token, signer || readProvider),
    reputation: new ethers.Contract(addresses.Reputation, abis.reputation, signer || readProvider),
    governance: new ethers.Contract(addresses.Governance, abis.governance, signer || readProvider),
    treasury: new ethers.Contract(addresses.Treasury, abis.treasury, signer || readProvider),
    registry: new ethers.Contract(addresses.ReportRegistry, abis.registry, signer || readProvider),
  };
}

function withSigner(contract) {
  if (!signer) throw new Error("Connect or generate a wallet first.");
  return contract.connect(signer);
}


// Wallet connection

document.getElementById("connectBtn").addEventListener("click", async () => {
  if (!window.ethereum) {
    alert("MetaMask (or another injected wallet) was not detected in this browser.");
    return;
  }
  provider = new ethers.BrowserProvider(window.ethereum);
  await provider.send("eth_requestAccounts", []);
  signer = await provider.getSigner();
  signerAddress = await signer.getAddress();
  const net = await provider.getNetwork();
  document.getElementById("networkBadge").textContent =
    `connected: ${signerAddress.slice(0, 6)}…${signerAddress.slice(-4)} (chainId ${net.chainId})`;
  await initContracts();
  await refreshValidatorReputation();
});

document.getElementById("addNetworkBtn").addEventListener("click", async () => {
  if (!window.ethereum) {
    alert("MetaMask (or another injected wallet) was not detected in this browser.");
    return;
  }
  try {
    await window.ethereum.request({
      method: "wallet_addEthereumChain",
      params: [UZH_ETH_POS],
    });
  } catch (err) {
    alert("Could not add the UZH_ETH_PoS network: " + (err.message || String(err)));
  }
});

document.getElementById("generateWalletBtn").addEventListener("click", async () => {
  // Generates a brand-new wallet in-browser, NOT linked to the user's
  // real-world identity by this app. The private key is shown once and
  // never transmitted anywhere; the user is responsible for saving it.
  // This wallet is connected to the same RPC endpoint as window.ethereum's
  // configured network so it can send transactions directly.
  const readProvider = await getReadProvider();
  const wallet = ethers.Wallet.createRandom().connect(readProvider);
  signer = wallet;
  signerAddress = wallet.address;
  document.getElementById("networkBadge").textContent =
    `fresh wallet: ${wallet.address.slice(0, 6)}…${wallet.address.slice(-4)}`;
  alert(
    "A new pseudonymous wallet was generated in your browser.\n\n" +
    `Address: ${wallet.address}\n` +
    `Private key: ${wallet.privateKey}\n\n` +
    "SAVE THIS PRIVATE KEY NOW — it is shown only once and is not stored anywhere. " +
    "You must fund this address with test ETH (for gas) and UZHETHs (for the stake) before submitting a report. " +
    "Remember: this wallet is pseudonymous, not fully anonymous — see the privacy note above."
  );
  await initContracts();
  document.getElementById("rWallet").value = wallet.address;
});


